function elf_maingui_visibility(gui, para, status)

col = {'r', [0 .5 0], [1 .6 0], 'g', [1 .6 0]};    % colors indicating analysis progress
tooltips = {{'No images were found in this folder.', ...
    'Only raw image files were found in this folder. Please convert them into uncompressed DNG files with Adobe''s DNG-Converter (see ELF manual for instructions).', ...
    'Images were found, but it appears that they were converted to DNG in the wrong way. Please review the conversion instructions (Help->Getting Started...)', ...
    'Usable images were found in this folder (either DNGs or non-raw). Proceed to the next step.', ...
    'Images were found, but an error occurred while reading them. Please refer to the error popup displayed during startup.'}, ...
    {'The scenes in this data set have not been processed yet. Press this button to start processing.', ...
    'Some, but not all of the scenes in this data set have been processed. Press this button to start processing.', ...
    'All scenes in this data set have been processed, but some of the raw files have been changed since then. Press this button to re-process all scenes or proceed to the next step.', ...
    'All scenes in this data set have been processed. Proceed to the next step or click here to re-process them all.', ...
    ''}, ...
    {'The mean image for this data set has not been calculated yet. Press this button to start calculating.', ...
    '', ...
    'A mean image for this data set has been calculated, but some of the images have been modified or re-processed since then. Press this button to re-calculate the mean image or proceed to the next step.', ...
    'The mean image for this data set has been calculated. Proceed to the next step or click here to re-calculate it.', ...
    ''}, ...
    {'The summary for this data set has not been calculated yet.', ...
    '', ...
    'A summary has been calculated, but some images have been modified or re-processed afterwards. Press this cutton to recalculate the summary.', ...
    'The summary has been calculated and saved for this data set.', ...
    ''}};

% set button colours
for i = 1:size(status.Colour, 1)
    set(gui.p(i).dng, 'backgroundcolor', status.Colour(i, 1).RGB, 'tooltip', status.Text{i, 1});
    set(gui.p(i).scenes, 'backgroundcolor', status.Colour(i, 2).RGB, 'tooltip', status.Text{i, 2});

    for modNum = length(para.modules):-1:1
        modName = para.modules{modNum};
        if para.ana.(modName).needsToRunPerEnvironment
            statusPos = 3+length(para.modules)-modNum; % the y-position of this module in the status arrays
            set(gui.p(i).modButtons(modNum), 'backgroundcolor', status.Colour(i, statusPos).RGB, 'tooltip', status.Text{i, statusPos});
        end
    end


    
    if status.Colour(i, 2)==StatusColour.Good, en = 'on'; else, en = 'off'; end % only enable exp button if scenes have been calculated
    set(gui.p(i).exp, 'enable', en);

    % TODO: Reenable this
    % if status.Colour(i, 4)==StatusColour.Good, en = 'on'; else, en = 'off'; end % only enable show button if summary has been calculated
    % set(gui.p(i).show, 'enable', en);
end